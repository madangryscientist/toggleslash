/** Renders docs/feature-parity.md from the parsed data. Deterministic: no dates, no git state. */

import type { Feature, ToggleSlashStatus, ParityData, Status } from "./parity-schema.ts";

const SYMBOL: Record<ToggleSlashStatus, string> = {
  yes: "✅",
  partial: "🟡",
  planned: "🚧",
  no: "❌",
};

const LEGEND = "✅ yes · 🟡 partial · 🚧 planned · ❌ no";

function symbol(status: ToggleSlashStatus): string {
  return SYMBOL[status];
}

function cell(text: string): string {
  return text.replaceAll("|", "\\|");
}

function categories(features: Feature[]): Map<string, Feature[]> {
  const grouped = new Map<string, Feature[]>();
  for (const feature of features) {
    const list = grouped.get(feature.category);
    if (list === undefined) grouped.set(feature.category, [feature]);
    else list.push(feature);
  }
  return grouped;
}

function count(data: ParityData, status: Status): number {
  return data.features.filter((feature) => feature.toggleslash.status === status).length;
}

function competitorCount(data: ParityData, competitorId: string, status: Status): number {
  return data.features.filter((feature) => feature.competitors[competitorId] === status).length;
}

function statusLabel(status: Status): string {
  if (status === "yes") return "✅ yes";
  if (status === "partial") return "🟡 partial";
  return "❌ no";
}

function summaryTable(data: ParityData): string[] {
  const header = [
    "| Metric | ToggleSlash |",
    ...data.competitors.map((competitor) => ` ${competitor.short} |`),
  ].join("");
  const divider = ["| --- | ---: |", ...data.competitors.map(() => " ---: |")].join("");
  const rows = (["yes", "partial", "no"] as const).map((status) => {
    const cells = [
      `${count(data, status)} |`,
      ...data.competitors.map((competitor) => ` ${competitorCount(data, competitor.id, status)} |`),
    ];
    return `| ${statusLabel(status)} | ${cells.join("")}`;
  });
  return [header, divider, ...rows];
}

function matrixTable(data: ParityData, features: Feature[]): string[] {
  const columns = data.competitors.map((competitor) => competitor.short);
  const header = `| Capability | ToggleSlash | ${columns.join(" | ")} |`;
  const divider = `| --- | :---: | ${columns.map(() => ":---:").join(" | ")} |`;
  const rows = features.map((feature) => {
    const cells = data.competitors.map((competitor) =>
      symbol(feature.competitors[competitor.id] ?? "no"),
    );
    return `| ${cell(feature.name)} | ${symbol(feature.toggleslash.status)} | ${cells.join(" | ")} |`;
  });
  return [header, divider, ...rows];
}

function evidenceCell(feature: Feature): string {
  if (feature.toggleslash.evidence.length === 0) return feature.toggleslash.note ?? "none";
  const evidence = feature.toggleslash.evidence.map((entry) => `\`${entry}\``).join("<br>");
  return feature.toggleslash.note === undefined
    ? evidence
    : `${evidence}<br>${cell(feature.toggleslash.note)}`;
}

function detailTable(features: Feature[]): string[] {
  const header = "| Capability | Status | Evidence and note |";
  const divider = "| --- | :---: | --- |";
  const rows = features.map(
    (feature) =>
      `| ${cell(feature.name)} | ${symbol(feature.toggleslash.status)} | ${evidenceCell(feature)} |`,
  );
  return [header, divider, ...rows];
}

function sources(data: ParityData): string[] {
  return data.sources.map((source) => `- [${source.name}](${source.url})`);
}

export function renderParity(data: ParityData): string {
  const lines: string[] = [
    "# Feature parity matrix",
    "",
    "> Generated from [`feature-parity.json`](feature-parity.json) by `bun run parity`. Do not edit this file by hand.",
    "",
    `**Last verified:** ${data.updated}. ${data.note}`,
    "",
    `**Legend:** ${LEGEND}.`,
    "",
    "## At a glance",
    "",
    "Counts are over the capabilities tracked below, not a market score. A broad product can be `no` on a",
    "capability it does not need, and a narrow one can be `yes` on the few it does.",
    "",
    ...summaryTable(data),
    "",
    "## Matrix",
    "",
  ];
  for (const [category, features] of categories(data.features)) {
    lines.push(`### ${category}`, "", ...matrixTable(data, features), "");
  }
  lines.push("## Where ToggleSlash stands", "");
  for (const [category, features] of categories(data.features)) {
    lines.push(`### ${category}`, "", ...detailTable(features), "");
  }
  lines.push(
    "## Sources",
    "",
    "Competitor cells were read from these public pages on the date above. They are a coarse reading,",
    "not a substitute for a current vendor comparison.",
    "",
    ...sources(data),
    "",
    "## How to update",
    "",
    "1. Change `docs/feature-parity.json`: the status, the evidence, the note, or a new capability.",
    "2. Run `bun run parity` to regenerate this file.",
    "3. Commit both files in the same commit.",
    "",
    "`bun run parity:check` runs in the gate. It fails when this file is stale, when a `yes` or",
    "`partial` has no evidence, when evidence points at a missing route or file, or when an API route,",
    "CLI command or dashboard route is not claimed by any capability.",
    "",
    "A commit whose subject starts with `feat` must change `docs/feature-parity.json`; CI checks the",
    "range between the base commit and `HEAD`.",
    "",
  );
  return lines.join("\n");
}
